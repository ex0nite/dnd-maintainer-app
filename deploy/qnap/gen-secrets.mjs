// Generates every secret of the QNAP stack (story 7.2, AD-10) into an env file OUTSIDE the repository.
//
//   node deploy/qnap/gen-secrets.mjs <env-file> <public-url> [account-domain]
//   e.g. node deploy/qnap/gen-secrets.mjs ~/dnd-stack/.env https://<your-host> table
//
// Nothing is printed except the path. The file is created with mode 600 and the script refuses to overwrite one:
// replacing a JWT secret signs every player out and invalidates the keys baked into a built front.

import { createHmac, randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const [target, publicUrl, accountDomain = 'table'] = process.argv.slice(2);

if (!target || !publicUrl) {
  process.stderr.write('Usage: node deploy/qnap/gen-secrets.mjs <env-file> <public-url> [account-domain]\n');
  process.exit(2);
}
if (!/^https?:\/\/[^\s/]+$/.test(publicUrl)) {
  process.stderr.write('public-url must look like https://host (no path, no trailing slash)\n');
  process.exit(2);
}
if (!/^[a-z0-9-]{1,30}$/.test(accountDomain)) {
  process.stderr.write('account-domain must match ^[a-z0-9-]{1,30}$\n');
  process.exit(2);
}

const file = resolve(target);
if (existsSync(file)) {
  process.stderr.write(`Refusing to overwrite ${file}\n`);
  process.exit(1);
}

const b64url = (buffer) => Buffer.from(buffer).toString('base64url');

function signJwt(role, secret) {
  const now = Math.floor(Date.now() / 1000);
  const header = b64url(JSON.stringify({ alg: 'HS256', typ: 'JWT' }));
  // Long-lived on purpose: the publishable key is public by design and is baked into the front bundle.
  const payload = b64url(JSON.stringify({ iss: 'supabase', role, iat: now, exp: now + 10 * 365 * 24 * 3600 }));
  const signature = b64url(createHmac('sha256', secret).update(`${header}.${payload}`).digest());
  return `${header}.${payload}.${signature}`;
}

const jwtSecret = randomBytes(48).toString('hex');
const lines = [
  '# Generated by deploy/qnap/gen-secrets.mjs. Never commit, never paste in a chat.',
  `PUBLIC_URL=${publicUrl}`,
  `ACCOUNT_DOMAIN=${accountDomain}`,
  `JWT_SECRET=${jwtSecret}`,
  `POSTGRES_PASSWORD=${randomBytes(24).toString('hex')}`,
  `ANON_KEY=${signJwt('anon', jwtSecret)}`,
  `SERVICE_ROLE_KEY=${signJwt('service_role', jwtSecret)}`,
  'JWT_EXPIRY=3600',
  '',
];

mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, lines.join('\n'), { mode: 0o600, flag: 'wx' });
process.stdout.write(`Secrets written to ${file} (mode 600)\n`);
